# ===================== РИСОВАЛКА "как на фото" =====================
def plot_hit_miss_pie(row, out_dir=".", show=True):
    hits = int(row["hits"])
    misses = int(row["misses"])
    total = hits + misses

    # На всякий случай: если total=0, чтобы не делить на 0
    if total == 0:
        hitrate = 0.0
        sizes = [1, 0]         # чтобы пирог вообще нарисовался
        labels = ["Промахи", "Попадания"]
    else:
        hitrate = 100.0 * hits / total
        sizes = [misses, hits]
        labels = ["Промахи", "Попадания"]

    title1 = f"Коэффициент попаданий кеша: {hitrate:.2f}%"
    title2 = f"VTPC direct={row['direct']}, bs={int(row['block_size'])}, file={int(row['file_size_mb'])}MB"

    fig, ax = plt.subplots(figsize=(12, 8))
    ax.pie(
        sizes,
        labels=labels,
        autopct="%1.1f%%",
        startangle=0,
        textprops={"fontsize": 18},
    )
    ax.set_title(f"{title1}\n{title2}", fontsize=22, pad=24)
    ax.axis("equal")

    # имя файла: чтобы не перетирались
    fname = (
        f"vtpc_pie_{row['type']}_direct-{row['direct']}_"
        f"bs-{int(row['block_size'])}_file-{int(row['file_size_mb'])}MB.png"
    )
    path = f"{out_dir.rstrip('/')}/{fname}"
    plt.savefig(path, dpi=200, bbox_inches="tight")

    if show:
        plt.show()
    else:
        plt.close(fig)

    return path

# ===================== СГЕНЕРИТЬ ВСЕ ПИРОГИ ДЛЯ vtpc =====================
# Будет по одному графику на каждую строку vtpc (т.е. для каждого набора параметров)
saved = []
for _, r in vt.iterrows():
    saved.append(plot_hit_miss_pie(r, out_dir=".", show=False))

print(f"Готово. Сохранено {len(saved)} png-файлов, пример:\n{saved[0]}")

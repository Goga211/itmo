plt.plot(f, phi_norm, label='ϕ')

plt.title('U(f)', fontsize=16)
plt.xlabel('F, Гц', fontsize=12)
plt.ylabel('U, В (отн.)', fontsize=12)

plt.grid(True, which='both', linestyle='--', linewidth=0.5, alpha=0.7)
plt.legend(loc='center right')
plt.xlim(f[0] - 50, f[-1] + 50)

plt.tight_layout()
plt.show()
